/** Stored annotation times are UTC Gregorian instants; null denotes an unknown creation time. */
export function validAnnotationTimestamp(value: string): boolean {
  const parts = /^([0-9]{4})-([0-9]{2})-([0-9]{2})T([0-9]{2}):([0-9]{2}):([0-9]{2})(\.[0-9]{1,6})?Z$/.exec(value);
  if (!parts || parts[0] !== value) return false;
  const [, year, month, day, hour, minute, second] = parts.map(Number);
  if (year < 1 || month < 1 || month > 12 || hour > 23 || minute > 59 || second > 59) return false;
  const leap = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  return day >= 1 && day <= [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1];
}
