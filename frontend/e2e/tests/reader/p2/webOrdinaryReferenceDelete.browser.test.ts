import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { test } from 'node:test';
import { committed, durable, resource } from './ordinaryStorage.ts';
import { gesture, ordinaryWeb } from './ordinaryWeb.ts';

for (const engine of ['chromium', 'webkit'] as const) test(`ordinary catalog deletion of pinned PDF preserves durable data (${engine})`, { timeout: 240_000 }, async t => {
  const app = await ordinaryWeb(t, engine), page = app.page;
  const root = path.resolve(import.meta.dirname, '../../../../..'), file = path.join(app.scratch, 'pinned-delete.pdf');
  const generated = spawnSync(path.join(root, '.venv/Scripts/python.exe'), [path.join(root, 'frontend/e2e/fixtures/p2PdfNavigation.py'), file], { encoding: 'utf8', windowsHide: true });
  assert.equal(generated.status, 0, generated.stderr);
  await page.getByLabel('取り込むPDF', { exact: true }).setInputFiles(file);
  await page.getByRole('heading', { name: 'pinned-delete.pdf', exact: true }).waitFor();
  const id = await page.locator('[data-content-document]').getAttribute('data-content-document'); assert.ok(id);
  const catalog = page.getByRole('button', { name: '資料一覧', exact: true });
  if (await catalog.getAttribute('aria-expanded') === 'true') await catalog.click();
  await page.locator('[data-reader-surface="original"] [data-rendered="true"] .react-pdf__Page canvas').waitFor();
  await page.getByRole('button', { name: 'ペン', exact: true }).click();
  await gesture(page, [[.2, .35], [.4, .45]], 'PDF書き込みレイヤー');
  const ink = await page.locator('[data-reader-surface="original"] [data-ink-id]').getAttribute('data-ink-id'); assert.ok(ink);
  const before = await durable(page, id, [ink], 1), background = before.root.pages[0].background;
  assert.equal(background.kind, 'pdf'); if (background.kind !== 'pdf') throw new Error('PDF background required');
  const stored = await resource(page, before.namespace, background.resourceId);
  assert.equal(stored.actualSha256, background.sourceRevision);
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).click();
  const reference = page.locator('[data-reader-reference]');
  await reference.locator('[data-rendered="true"] .react-pdf__Page__canvas').waitFor();
  const pinned = await reference.locator('[data-canonical-page]').getAttribute('data-canonical-page'); assert.ok(pinned);
  await page.getByRole('button', { name: '文字', exact: true }).click();
  await gesture(page, [[.2, .7]], 'PDF書き込みレイヤー');
  const draft = page.getByRole('textbox', { name: '書き込みテキスト', exact: true }); await draft.fill('削除を待つ下書き');
  if (await catalog.getAttribute('aria-expanded') !== 'true') await catalog.click();
  await page.getByRole('button', { name: '「pinned-delete.pdf」を削除', exact: true }).click();
  await page.getByRole('button', { name: '削除を確定', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '未保存または送信待ちの編集があるため削除できません' }).waitFor();
  assert.equal(await page.locator('[data-content-document]').getAttribute('data-content-document'), id);
  await draft.waitFor(); assert.equal(await draft.inputValue(), '削除を待つ下書き');
  await reference.locator(`[data-canonical-page="${pinned}"]`).waitFor();
  assert.deepEqual(await committed(page, id), before);
  await page.getByRole('button', { name: '削除を取り消す', exact: true }).click();
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click();
  await page.getByRole('button', { name: '「pinned-delete.pdf」を削除', exact: true }).click();
  await page.getByRole('button', { name: '削除を確定', exact: true }).click();
  await page.getByRole('region', { name: '削除した資料', exact: true }).waitFor();
  await page.getByRole('button', { name: '削除された「pinned-delete.pdf」の内容を確認', exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('[data-reader-reference] [data-pdf-surface]') && !document.querySelector('[data-reader-surface] [data-ink-overlay]'));
  assert.equal(await page.locator('[data-reader-reference] [data-pdf-surface]').count(), 0);
  assert.deepEqual(await committed(page, id), before);
  assert.deepEqual(await resource(page, before.namespace, background.resourceId), stored);
  const reopened = await app.restartLibrary();
  const reopenedCatalog = reopened.getByRole('button', { name: '資料一覧', exact: true });
  if (await reopenedCatalog.getAttribute('aria-expanded') !== 'true') await reopenedCatalog.click();
  await reopened.getByRole('button', { name: '削除された「pinned-delete.pdf」の内容を確認', exact: true }).waitFor();
  assert.equal(await reopened.getByRole('button', { name: 'pinned-delete.pdf', exact: true }).count(), 0);
  assert.deepEqual(await committed(reopened, id), before);
  assert.deepEqual(await resource(reopened, before.namespace, background.resourceId), stored);
  t.diagnostic(JSON.stringify({ engine, documentId: id, pinnedDraftDeleteRefused: true, catalogDeleted: true,
    editorAndReferenceRemoved: true, retainedExactRootBatchReceiptAndResource: true, deletionSurvivesColdBrowserRestart: true }));
});
