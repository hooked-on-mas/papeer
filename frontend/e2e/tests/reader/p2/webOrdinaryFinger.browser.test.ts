import assert from 'node:assert/strict';
import { test } from 'node:test';
import path from 'node:path';
import { committed, durable, inks } from './ordinaryStorage.ts';
import { createNotebook, ordinaryWeb } from './ordinaryWeb.ts';

test('ordinary P2 trusted finger ink cancels for pinch, drains and preserves pen with palm', { timeout: 180_000 }, async t => {
  const app = await ordinaryWeb(t, 'chromium'), page = app.page;
  const documentId = await createNotebook(page, 'P2 finger ink');
  await page.getByRole('button', { name: 'ペン', exact: true }).click();
  await page.getByLabel('指で描く', { exact: true }).check();
  const layer = page.getByLabel('ノート書き込みレイヤー', { exact: true });
  await layer.scrollIntoViewIfNeeded();
  const box = await layer.boundingBox(); assert.ok(box);
  const point = (id: number, x: number, y: number) => ({ id, x: box.x + box.width * x, y: box.y + box.height * y });
  const cdp = await page.context().newCDPSession(page);
  const touch = (type: 'touchStart' | 'touchMove' | 'touchEnd' | 'touchCancel', touchPoints: { id: number; x: number; y: number }[]) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints });
  await touch('touchStart', [point(0, .2, .25)]);
  await touch('touchMove', [point(0, .45, .25)]);
  await touch('touchEnd', []);
  await page.waitForFunction(() => document.querySelectorAll('[data-ink-id]').length === 1);
  const original = await inks(page), ids = original.map(value => value.id);
  await durable(page, documentId, ids, 1);
  await page.getByLabel('倍率', { exact: true }).selectOption('1');
  const viewport = await layer.boundingBox(); assert.ok(viewport);
  const center = { x: viewport.x + viewport.width * .5, y: Math.min(viewport.y + viewport.height * .5, 750) };
  const fingers = (gap: number) => [{ id: 0, x: center.x - gap, y: center.y }, { id: 1, x: center.x + gap, y: center.y }];
  await touch('touchStart', [fingers(40)[0]]);
  await touch('touchMove', [{ ...fingers(40)[0], x: center.x - 20 }]);
  assert.equal((await committed(page, documentId)).edits.length, 1, 'preview is not a durable edit');
  await touch('touchStart', fingers(40));
  await touch('touchMove', fingers(80));
  await touch('touchEnd', [fingers(80)[0]]);
  await touch('touchMove', [{ ...fingers(80)[0], x: center.x - 50 }]);
  await touch('touchEnd', []);
  await page.waitForFunction(() => Number((document.querySelector('[aria-label="倍率"]') as HTMLSelectElement)?.value) > 1.2);
  assert.deepEqual(await inks(page), original, 'second finger cancels preview and remaining finger cannot reenter ink');
  assert.equal((await committed(page, documentId)).edits.length, 1);

  await page.getByLabel('倍率', { exact: true }).selectOption('0');
  await layer.scrollIntoViewIfNeeded();
  const penBox = await layer.boundingBox(); assert.ok(penBox);
  const pen = (x: number) => ({ x: penBox.x + penBox.width * x, y: penBox.y + penBox.height * .65 });
  await cdp.send('Input.dispatchMouseEvent', { type: 'mousePressed', ...pen(.2), button: 'left', buttons: 1, pointerType: 'pen', force: .7 });
  await cdp.send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...pen(.35), buttons: 1, pointerType: 'pen', force: .7 });
  await touch('touchStart', [{ id: 2, x: penBox.x + penBox.width * .7, y: penBox.y + penBox.height * .55 }]);
  await touch('touchEnd', []);
  await cdp.send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...pen(.5), buttons: 1, pointerType: 'pen', force: .7 });
  await cdp.send('Input.dispatchMouseEvent', { type: 'mouseReleased', ...pen(.5), button: 'left', buttons: 0, pointerType: 'pen' });
  await page.waitForFunction(() => document.querySelectorAll('[data-ink-id]').length === 2);
  const withPen = (await inks(page)).map(value => value.id);
  await durable(page, documentId, withPen, 2);
  await cdp.detach();
  const reopened = await app.restart('P2 finger ink');
  assert.equal(await reopened.getByLabel('指で描く', { exact: true }).isChecked(), true);
  await durable(reopened, documentId, withPen, 2);
  const catalog = reopened.getByRole('button', { name: '資料一覧', exact: true });
  if (await catalog.getAttribute('aria-expanded') !== 'true') await catalog.click();
  await reopened.getByLabel('取り込むPDF', { exact: true }).setInputFiles(path.resolve(import.meta.dirname, '../../../../../tests/fixtures/shared-coordinate-pages.pdf'));
  await reopened.getByRole('heading', { name: 'shared-coordinate-pages.pdf', exact: true }).waitFor();
  const pdfId = await reopened.locator('[data-content-document]').getAttribute('data-content-document'); assert.ok(pdfId);
  await reopened.getByRole('button', { name: '資料一覧', exact: true }).click();
  await reopened.getByRole('button', { name: 'ペン', exact: true }).click();
  const pdfLayer = reopened.getByLabel('PDF書き込みレイヤー', { exact: true }); await pdfLayer.scrollIntoViewIfNeeded();
  const pdfBox = await pdfLayer.boundingBox(); assert.ok(pdfBox);
  const pdfCdp = await reopened.context().newCDPSession(reopened);
  await pdfCdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ id: 0, x: pdfBox.x + pdfBox.width * .2, y: pdfBox.y + pdfBox.height * .3 }] });
  await pdfCdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ id: 0, x: pdfBox.x + pdfBox.width * .45, y: pdfBox.y + pdfBox.height * .3 }] });
  await pdfCdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await reopened.waitForFunction(() => document.querySelectorAll('[data-ink-id]').length === 1);
  const pdfIds = (await inks(reopened)).map(value => value.id); await durable(reopened, pdfId, pdfIds, 1);
  await pdfCdp.detach();
  t.diagnostic(JSON.stringify({ documentId, fingerBatch: 1, canceledPreviewBatches: 0, penWithPalmBatch: 1,
    pdfId, pdfFingerBatch: 1, fingerPreferenceRestored: true, input: 'trusted Chromium CDP touch and pen; not OS stylus hardware acceptance' }));
});
