import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { test } from 'node:test';
import { committed } from './ordinaryStorage.ts';
import { createNotebook, gesture, ordinaryWeb } from './ordinaryWeb.ts';

for (const engine of ['chromium', 'webkit'] as const) test(`ordinary PDF fixed reference and draft guard (${engine})`, { timeout: 180_000 }, async t => {
  const app = await ordinaryWeb(t, engine), page = app.page;
  const root = path.resolve(import.meta.dirname, '../../../../..'), file = path.join(app.scratch, 'p2-reference.pdf');
  const authored = spawnSync(path.join(root, '.venv/Scripts/python.exe'), [path.join(root, 'frontend/e2e/fixtures/p2PdfNavigation.py'), file], { encoding: 'utf8', windowsHide: true });
  assert.equal(authored.status, 0, authored.stderr);
  await page.getByLabel('取り込むPDF', { exact: true }).setInputFiles(file);
  await page.getByRole('heading', { name: 'p2-reference.pdf', exact: true }).waitFor();
  const id = await page.locator('[data-content-document]').getAttribute('data-content-document'); assert.ok(id);
  await page.getByRole('button', { name: '資料一覧', exact: true }).click();
  const before = await committed(page, id);
  const ref = page.locator('[data-reader-reference]');
  await page.locator('[data-reader-surface="original"] .react-pdf__Page[data-page-number="1"] canvas').waitFor();
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).click();
  await ref.locator('.react-pdf__Page[data-page-number="1"] canvas').waitFor();
  assert.equal(await page.getByLabel('ページ番号', { exact: true }).inputValue(), '1');
  assert.equal(await ref.locator('[data-ink-overlay], [aria-label$="書き込みレイヤー"]').count(), 0);
  await page.getByRole('button', { name: '次のページ', exact: true }).click();
  assert.equal(await page.getByLabel('ページ番号', { exact: true }).inputValue(), '2');
  await ref.locator('.react-pdf__Page[data-page-number="1"]').waitFor();
  await page.getByRole('button', { name: '現在のページに置き換える', exact: true }).click();
  await ref.locator('.react-pdf__Page[data-page-number="2"] canvas').waitFor();
  assert.equal(await page.getByLabel('ページ番号', { exact: true }).inputValue(), '2');
  const referenceIdentity = await ref.locator('[data-canonical-page]').evaluate(element => ({ page: element.getAttribute('data-canonical-page'), revision: element.getAttribute('data-background-revision') }));
  const route = () => page.evaluate(documentId => {
    const prefix = 'paper-desk.reader.v1:';
    const key = Object.keys(localStorage).find(k => k.startsWith(prefix) && JSON.parse(k.slice(prefix.length))[3] === documentId);
    if (!key) throw new Error('reader preference unavailable');
    const saved = JSON.parse(localStorage.getItem(key)!);
    const location = (entry: { place?: unknown }) => { const { place: _place, ...rest } = entry; return rest; };
    return { pageId: saved.pageId, back: saved.back.map(location), forward: saved.forward.map(location) };
  }, id);
  const beforeSameTarget = await route();
  await page.getByRole('button', { name: '現在のページに置き換える', exact: true }).click();
  await ref.locator(`[data-canonical-page="${referenceIdentity.page}"]`).waitFor();
  assert.deepEqual(await ref.locator('[data-canonical-page]').evaluate(element => ({ page: element.getAttribute('data-canonical-page'), revision: element.getAttribute('data-background-revision') })), referenceIdentity);
  assert.deepEqual(await route(), beforeSameTarget, 'same-target reference replacement does not change main page or history');
  const main = page.locator('[data-reader-surface="original"] [data-pdf-surface]');
  const surface = ref.locator('[data-pdf-surface]');
  await ref.locator('[data-pdf-scroller][data-rendered="true"]').waitFor();
  const width = await surface.evaluate(e => e.getBoundingClientRect().width);
  const mainWidth = await main.evaluate(e => e.getBoundingClientRect().width);
  await ref.focus(); await page.keyboard.press('Control+Equal');
  await page.waitForFunction(old => (document.querySelector('[data-reader-reference] [data-pdf-surface]')?.getBoundingClientRect().width ?? 0) > old + 1, width);
  assert.ok(Math.abs((await main.evaluate(e => e.getBoundingClientRect().width)) - mainWidth) < 2);
  await page.setViewportSize({ width: 1320, height: 950 });
  await ref.locator('.react-pdf__Page[data-page-number="2"] canvas').waitFor();
  await page.getByRole('button', { name: '中央で編集', exact: true }).click();
  assert.equal(await ref.count(), 0, 'center placement hides the reference');
  await page.getByRole('button', { name: '右側で編集', exact: true }).click();
  await ref.locator('.react-pdf__Page[data-page-number="2"] canvas').waitFor();
  await page.getByRole('button', { name: '文字', exact: true }).click();
  await gesture(page, [[.2, .4]], 'PDF書き込みレイヤー');
  await page.getByRole('textbox', { name: '書き込みテキスト', exact: true }).fill('未確定');
  await page.getByRole('button', { name: '固定を解除', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: /入力や保存/ }).waitFor();
  await ref.locator('.react-pdf__Page[data-page-number="2"]').waitFor();
  await page.getByRole('textbox', { name: '書き込みテキスト', exact: true }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: '書き込みテキスト', exact: true }).inputValue(), '未確定');
  await page.getByRole('button', { name: 'ライブラリを切り替える', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: /入力を確定/ }).waitFor();
  assert.equal(await page.locator('[data-content-document]').getAttribute('data-content-document'), id);
  await page.getByRole('textbox', { name: '書き込みテキスト', exact: true }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: '書き込みテキスト', exact: true }).inputValue(), '未確定');
  await ref.locator('.react-pdf__Page[data-page-number="2"]').waitFor();
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click();
  await page.getByRole('button', { name: '固定を解除', exact: true }).click();
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).waitFor();
  assert.equal(await page.getByLabel('ページ番号', { exact: true }).inputValue(), '2');
  const after = await committed(page, id); assert.deepEqual(after.root, before.root); assert.equal(after.edits.length, 0);
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).click();
  await page.getByRole('button', { name: 'ライブラリを切り替える', exact: true }).click();
  await page.getByRole('button', { name: app.library, exact: true }).click();
  await page.getByRole('heading', { name: 'p2-reference.pdf', exact: true }).waitFor();
  assert.equal(await page.locator('[data-content-document]').getAttribute('data-content-document'), id);
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).waitFor();
  const restoredCatalog=page.getByRole('button', { name: '資料一覧', exact: true });
  if(await restoredCatalog.getAttribute('aria-expanded')!=='true')await restoredCatalog.click();
  await page.getByLabel('\u65b0\u3057\u3044\u8cc7\u6599\u306e\u540d\u524d', {exact:true}).waitFor();
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).click();
  await createNotebook(page, `other ${engine}`);
  await page.getByRole('button', { name: 'p2-reference.pdf', exact: true }).click();
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).waitFor();
  await page.getByRole('button', { name: 'このページを参照に固定', exact: true }).click();
  const reopened = await app.restart('p2-reference.pdf');
  await reopened.getByRole('button', { name: 'このページを参照に固定', exact: true }).waitFor();
  assert.equal((await committed(reopened, id)).edits.length, 0);
  t.diagnostic(JSON.stringify({ engine, id, pages: 'pin 1, replace 2', independentZoom: true, resize: true, placement: true, draftGuard: true, ephemeralOnRestart: true, editBatches: 0 }));
});
