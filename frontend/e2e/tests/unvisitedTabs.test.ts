import assert from "node:assert/strict";
import { scenario } from "../lib/app.ts";
import { waitFor } from "../lib/processes.ts";
import { openPaper, waitForLibrary } from "../lib/ui.ts";

scenario("翻訳範囲と共用辞書の入力・検索・保存", { papers: [{ file: "observer.pdf" }] }, async app => {
  const { page, api } = app;
  await waitForLibrary(page, ["Robust Observer"]);
  await openPaper(page, "Robust Observer");
  await page.getByRole("button", { name: "翻訳する…", exact: true }).click();
  const dialog = page.getByRole("dialog");
  const scope = dialog.getByRole("combobox", { name: "翻訳するページ", exact: true });
  assert.equal(await dialog.getByRole("textbox", { name: "翻訳するページ番号", exact: true }).count(), 0);
  await scope.selectOption("custom");
  await dialog.getByRole("textbox", { name: "翻訳するページ番号", exact: true }).fill("");
  assert.equal(await dialog.getByRole("button", { name: "翻訳を開始", exact: true }).isDisabled(), true);
  await scope.selectOption("current");
  assert.equal(await dialog.getByRole("textbox", { name: "翻訳するページ番号", exact: true }).count(), 0);
  await dialog.getByRole("button", { name: "訳語の修正", exact: true }).click();
  await dialog.getByText("訳語の一覧・辞書を管理（詳細設定）", { exact: true }).click();
  await dialog.getByText("使う分野を変更", { exact: true }).click();
  await dialog.getByRole("button", { name: "共用辞書を管理", exact: true }).click();
  await dialog.getByText("辞書は空です。「手動で用語を追加」から登録できます。", { exact: true }).waitFor();
  await dialog.getByRole("button", { name: "手動で用語を追加", exact: true }).click();
  const source = dialog.getByRole("textbox", { name: "原語 1", exact: true });
  await waitFor(() => source.evaluate(el => el === document.activeElement), "追加した原語欄へ移動");
  await source.fill("gradient");
  await dialog.getByRole("textbox", { name: "訳語 1", exact: true }).fill("勾配");
  assert.equal(await dialog.getByRole("button", { name: "gradientを辞書から削除", exact: true }).count(), 1);
  const search = dialog.getByRole("textbox", { name: "辞書を検索", exact: true });
  await search.fill("  gradient  ");
  assert.equal(await source.isVisible(), true);
  await search.fill("存在しない用語");
  await dialog.getByText("条件に一致する用語はありません。検索語や絞り込みを変えてください。", { exact: true }).waitFor();
  await dialog.getByRole("button", { name: "辞書の検索語を消す", exact: true }).click();
  assert.equal(await search.inputValue(), "");
  assert.equal(await search.evaluate(el => el === document.activeElement), true);
  await dialog.getByRole("button", { name: "辞書を保存", exact: true }).click();
  await waitFor(async () => (await api.call("GET", "/api/glossary")).some((t: { source: string }) => t.source === "gradient"), "辞書が保存される");
  await dialog.getByRole("button", { name: "キャンセル", exact: true }).click();
  assert.deepEqual(app.consoleErrors.filter(e => e.startsWith("[pageerror]")), []);
});

scenario("空の論文マップと条件解除、同期説明、読書状態の追加", { papers: [{ file: "observer.pdf" }], viewport: { width: 986, height: 763 } }, async app => {
  const { page, api } = app;
  await api.call("PUT", "/api/settings", { paper_discovery_enabled: false });
  await waitForLibrary(page, ["Robust Observer"]);
  await openPaper(page, "Robust Observer");
  await page.getByRole("tab", { name: "論文マップ", exact: true }).click();
  const map = page.getByRole("region", { name: "論文マップ", exact: true });
  await map.getByRole("combobox", { name: "登録状態", exact: true }).waitFor();
  assert.equal(await map.getByRole("button", { name: "戻る", exact: true }).count(), 0);
  assert.equal(await map.locator("summary", { hasText: "つながりのまとまり" }).count(), 0);
  const legend = map.locator("details").filter({ has: page.locator("summary", { hasText: "図の見方" }) });
  assert.equal(await legend.getAttribute("open"), null);
  assert.ok((await legend.boundingBox())!.y < await page.evaluate(() => window.innerHeight), "空の図では凡例まで画面内に表示");
  await map.getByRole("combobox", { name: "登録状態", exact: true }).selectOption("external");
  const search = map.getByRole("textbox", { name: "論文を検索", exact: true });
  await search.fill("見つからない論文");
  await map.getByRole("button", { name: "論文マップの検索語を消す", exact: true }).click();
  assert.equal(await search.inputValue(), "");
  assert.equal(await search.evaluate(el => el === document.activeElement), true);
  assert.equal(await map.getByRole("combobox", { name: "登録状態", exact: true }).inputValue(), "external");
  await map.getByRole("button", { name: "表示条件をリセット", exact: true }).click();
  assert.equal(await map.getByRole("combobox", { name: "登録状態", exact: true }).inputValue(), "all");
  await page.getByRole("button", { name: "接続・設定", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "設定", exact: true });
  const nav = settings.getByRole("navigation", { name: "設定の項目", exact: true });
  await nav.getByRole("button", { name: "読書状態", exact: true }).click();
  const name = settings.getByRole("textbox", { name: "新しい読書状態名", exact: true });
  await name.fill("要照合");
  await settings.getByRole("button", { name: "追加", exact: true }).click();
  await settings.getByText("「要照合」を追加しました。", { exact: true }).waitFor();
  await waitFor(() => name.evaluate(el => el === document.activeElement), "追加後に次の名前を入力できる");
  await nav.getByRole("button", { name: "付箋の分類", exact: true }).click();
  const category = settings.getByRole("textbox", { name: "新しい付箋の分類名", exact: true });
  await category.fill("あ".repeat(43));
  assert.equal((await category.inputValue()).length, 40);
  await settings.getByText("名前は40文字まで（40/40文字）。", { exact: true }).waitFor();
  await settings.getByRole("button", { name: "「重要」を削除", exact: true }).click();
  await settings.getByRole("button", { name: "削除をやめる", exact: true }).click();
  assert.equal(await settings.getByRole("button", { name: "「重要」を削除", exact: true }).count(), 1);
  await nav.getByRole("button", { name: "保存先・同期", exact: true }).click();
  for (const label of ["同期する内容", "別のPCで使うときの注意"]) {
    const detail = settings.locator("details").filter({ has: page.locator("summary", { hasText: label }) });
    await detail.locator("summary").waitFor();
    assert.equal(await detail.getAttribute("open"), null);
    await detail.locator("summary").click();
    assert.ok((await detail.innerText()).length > label.length + 30);
  }
  await settings.getByRole("checkbox", { name: "別のPCで追加された未対応の設定を知らせる", exact: true }).waitFor();
  await settings.getByRole("button", { name: "閉じる", exact: true }).click();
  assert.deepEqual(app.consoleErrors.filter(e => e.startsWith("[pageerror]")), []);
});

scenario("訳文修正の段落番号、選択後の入力位置と一覧の再展開", { papers: [{ file: "observer.pdf" }], timeout: 300_000 }, async app => {
  const { page, api } = app;
  const id = app.paperIds["observer.pdf"];
  const job = await api.call("POST", `/api/papers/${id}/translate`, { pages: "1" });
  await api.job(job.job_id);
  await waitForLibrary(page, ["Robust Observer"]);
  await openPaper(page, "Robust Observer");
  await page.getByRole("button", { name: "その他の表示・操作", exact: true }).click();
  await page.getByRole("menuitem", { name: /翻訳の確認・修正/ }).click();
  const dialog = page.getByRole("dialog", { name: "翻訳の確認・修正", exact: true });
  await dialog.getByRole("button", { name: "翻訳を修正", exact: true }).click();
  for (const n of [1, 2]) {
    if (n === 2) await dialog.locator("summary", { hasText: "段落一覧" }).click();
    const paragraph = dialog.getByRole("button", { name: new RegExp(`^p\\.1 段落${n} `) });
    await paragraph.click();
    const editor = dialog.getByRole("textbox", { name: "訳文の修正案", exact: true });
    await waitFor(() => editor.evaluate(el => el === document.activeElement), "選んだ段落の修正案へ移動");
    const list = dialog.locator("details").filter({ has: page.locator("summary", { hasText: "段落一覧" }) });
    assert.equal(await list.getAttribute("open"), null);
    await dialog.getByText(`編集中：p.1 段落${n}`, { exact: true }).waitFor();
    assert.equal(await dialog.getByRole("button", { name: "採用してPDFに反映", exact: true }).isDisabled(), true);
  }
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  assert.deepEqual(app.consoleErrors.filter(e => e.startsWith("[pageerror]")), []);
});
