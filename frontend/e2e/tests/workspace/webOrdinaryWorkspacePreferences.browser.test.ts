import assert from 'node:assert/strict';
import { test } from 'node:test';
import { ordinaryWeb } from '../reader/p2/ordinaryWeb.ts';
import { ordinaryMarkdownSaved } from '../../support/ordinaryMarkdown.ts';

for (const engine of ['chromium', 'webkit'] as const) test(`ordinary scoped display and catalog preferences survive restart (${engine})`, { timeout: 180_000 }, async t => {
  const app = await ordinaryWeb(t, engine), page = app.page, title = `P4 display ${engine}`;
  let phase = 'create', current = page;
  try {
    await page.getByRole('button', { name: '新規', exact: true }).click();
    const createDialog = page.getByRole('dialog', { name: '新しい資料を作成', exact: true });
    await createDialog.getByLabel('新しい資料の名前', { exact: true }).fill(title);
    await createDialog.getByLabel('資料の種類', { exact: true }).selectOption('markdown');
    await createDialog.getByRole('button', { name: '資料を作成', exact: true }).click();
    await createDialog.waitFor({ state: 'hidden' });
    await page.getByRole('heading', { name: title, exact: true }).waitFor();
    const editor = page.getByRole('textbox', { name: 'Markdownノート', exact: true }); await editor.waitFor();
    const id = await page.locator('[data-content-document]').getAttribute('data-content-document'); assert.ok(id);
    await editor.fill('表示設定で本文を変更しない\n'); await editor.blur();
    const saved = await ordinaryMarkdownSaved(page, id, '表示設定で本文を変更しない\n', 1);
    await page.getByRole('button', { name: '右側で編集', exact: true }).click();
    await page.locator('[data-editor-placement="right"]').waitFor();
    phase = 'display';
    await page.getByRole('button', { name: '表示設定', exact: true }).click();
    const settings = page.getByRole('dialog', { name: 'このライブラリの表示設定', exact: true }); await settings.waitFor();
    await settings.getByLabel('配色', { exact: true }).selectOption('dark');
    await settings.getByLabel('文字の大きさ', { exact: true }).selectOption('1.25');
    await settings.getByLabel('サイドバーの幅', { exact: true }).selectOption('320');
    await settings.getByLabel('右側の編集幅', { exact: true }).selectOption('60');
    await settings.getByRole('button', { name: '表示設定を閉じる', exact: true }).click(); await settings.waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark' && document.documentElement.style.fontSize === '125%');
    const workspace = await page.locator('[data-editor-placement="right"]').boundingBox();
    const right = await page.getByRole('complementary', { name: '右側の編集', exact: true }).boundingBox();
    assert.ok(workspace && right && Math.abs(right.width / workspace.width - .6) < .015, 'rendered editor width follows its saved setting');
    const sidebarBox = await page.locator('#workspace-catalog-chrome').boundingBox();
    assert.ok(sidebarBox && Math.abs(sidebarBox.width - 320) < 2, `rendered sidebar width ${sidebarBox?.width} follows 320px`);
    phase = 'restart-open';
    const reopened = await app.restartLibrary({ showCatalog: false }); current = reopened;
    await reopened.waitForFunction(() => document.documentElement.dataset.theme === 'dark' && document.documentElement.style.fontSize === '125%');
    const restoredCatalog = reopened.getByRole('button', { name: '資料一覧', exact: true });
    assert.equal(await restoredCatalog.getAttribute('aria-expanded'), 'true');
    await reopened.getByRole('button', { name: title, exact: true }).click();
    await reopened.getByRole('heading', { name: title, exact: true }).waitFor();
    await reopened.getByRole('textbox', { name: 'Markdownノート', exact: true }).waitFor();
    assert.deepEqual(await ordinaryMarkdownSaved(reopened, id, '表示設定で本文を変更しない\n', 1), saved);
    await restoredCatalog.click();
    assert.equal(await restoredCatalog.getAttribute('aria-expanded'), 'false', 'closing the sidebar saves catalogOpen=false');
    phase = 'restart-closed';
    const final = await app.restartLibrary({ showCatalog: false }); current = final;
    assert.equal(await final.getByRole('button', { name: '資料一覧', exact: true }).getAttribute('aria-expanded'), 'false');
    await final.getByRole('button', { name: '表示設定', exact: true }).click();
    const restoredSettings = final.getByRole('dialog', { name: 'このライブラリの表示設定', exact: true });
    assert.equal(await restoredSettings.getByLabel('配色', { exact: true }).inputValue(), 'dark');
    assert.equal(await restoredSettings.getByLabel('文字の大きさ', { exact: true }).inputValue(), '1.25');
    assert.equal(await restoredSettings.getByLabel('サイドバーの幅', { exact: true }).inputValue(), '320');
    assert.equal(await restoredSettings.getByLabel('右側の編集幅', { exact: true }).inputValue(), '60');
    t.diagnostic(JSON.stringify({ engine, documentId: id, theme: 'dark', uiScale: 1.25, catalogOpenAndClosedRestored: true, contentEdits: 1, coldRestarts: 2 }));
  } catch (error) { console.error(JSON.stringify({ phase, error: String(error), body: await current.locator('body').innerText().catch(String) })); throw error; }
});
