import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs';
import { test } from 'node:test';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';

test('Web notes create Markdown and handwriting, retain edits and work at mobile width', { timeout: 120000 }, async t => {
  const frontend = path.resolve(import.meta.dirname, '..');
  const server = await createServer({ root: frontend, configFile: path.join(frontend, 'vite.config.ts'), logLevel: 'error', server: { host: '127.0.0.1', port: 0, hmr: false, fs: { allow: [path.resolve(frontend, '..')] } } });
  await server.listen(); t.after(() => server.close());
  const browser = await chromium.launch({ channel: 'msedge', headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1000, height: 900 } });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(server.resolvedUrls!.local[0] + 'e2e/fixtures/unifiedNotes.html');
  await page.getByRole('button', { name: '＋ ノートを作る' }).click();
  await page.getByLabel('種類').selectOption('markdown');
  await page.getByLabel('ノート名').fill('研究Markdown');
  await page.getByRole('button', { name: '作成', exact: true }).click();
  const editor = page.getByRole('textbox', { name: 'Markdownノート' });
  await editor.fill('# 検証\n\n保存されるノート');
  await page.getByRole('button', { name: 'プレビュー', exact: true }).click();
  await page.getByRole('heading', { name: '検証', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('[role=status]')?.textContent === 'Driveへ同期済み');
  await page.getByRole('button', { name: '戻る', exact: true }).click();
  await page.getByRole('button', { name: /研究Markdown/ }).click();
  assert.match(await editor.innerText(), /保存されるノート/);
  await page.getByRole('button', { name: '戻る', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '＋ ノートを作る' }).click();
  await page.getByLabel('種類').selectOption('notebook');
  await page.getByLabel('ノート名').fill('手書き検証');
  await page.getByRole('button', { name: '作成', exact: true }).click();
  const paper = page.getByLabel('手書きノートの用紙');
  await paper.scrollIntoViewIfNeeded();
  const rect = (await paper.boundingBox())!;
  await page.mouse.move(rect.x + rect.width * .3, rect.y + rect.height * .3);
  await page.mouse.down(); await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .4, { steps: 8 }); await page.mouse.up();
  assert.equal(await paper.locator('polyline').count(), 1);
  await page.getByRole('button', { name: '＋ ページ', exact: true }).click();
  assert.equal(await page.getByLabel('ページ', { exact: true }).inputValue() !== '', true);
  assert.equal(await page.getByLabel('ページ', { exact: true }).locator('option').count(), 2);
  await page.getByLabel('ページ', { exact: true }).selectOption({ index: 0 });
  assert.equal(await paper.locator('polyline').count(), 1);
  const output = path.resolve(frontend, '../output/unified-notes'); fs.mkdirSync(output, { recursive: true });
  await page.screenshot({ path: path.join(output, 'mobile-handwriting.png'), fullPage: true });
  assert.deepEqual(errors, []);
});
