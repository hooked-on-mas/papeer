"""Generate finite edit wire types/structural validators for both runtimes from one schema.

Run `python tools/generate_edit_contracts.py --check` in CI to detect drift.
Business rules live in edit_model.py / editModel.ts and use the same fixture corpus.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema/edit-contracts.json"


def ts_type(spec: dict) -> str:
    if "$ref" in spec:
        return spec["$ref"].rsplit("/", 1)[1]
    if "const" in spec:
        return json.dumps(spec["const"])
    if "enum" in spec:
        return " | ".join(json.dumps(value) for value in spec["enum"])
    if "oneOf" in spec:
        return " | ".join(ts_type(value) for value in spec["oneOf"])
    kind = spec["type"]
    if kind == "array":
        return f"({ts_type(spec['items'])})[]"
    if kind == "object":
        if "properties" not in spec:
            return f"Record<string, {ts_type(spec['additionalProperties'])}>"
        required = spec.get("required", [])
        return "{ " + "; ".join(f"{key}{'' if key in required else '?'}: {ts_type(value)}" for key, value in spec["properties"].items()) + " }"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}[kind]


def py_type(spec: dict) -> str:
    if "$ref" in spec:
        return spec["$ref"].rsplit("/", 1)[1]
    if "const" in spec:
        return f"Literal[{spec['const']!r}]"
    if "enum" in spec:
        return f"Literal[{', '.join(repr(value) for value in spec['enum'])}]"
    if "oneOf" in spec:
        return " | ".join(py_type(value) for value in spec["oneOf"])
    kind = spec["type"]
    if kind == "array":
        return f"list[{py_type(spec['items'])}]"
    if kind == "object":
        return f"dict[str, {py_type(spec['additionalProperties'])}]"
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "null": "None"}[kind]


def outputs() -> dict[Path, str]:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    allowed = {"$ref", "const", "enum", "oneOf", "type", "properties", "required", "additionalProperties", "items",
               "minItems", "maxItems", "minLength", "maxLength", "minimum", "maximum", "exclusiveMinimum", "pattern"}

    def check(rule):
        unknown = set(rule) - allowed
        if unknown:
            raise ValueError(f"Unsupported edit schema keywords: {sorted(unknown)}")
        if "$ref" in rule and rule["$ref"].rsplit("/", 1)[1] not in schema["$defs"]:
            raise ValueError(f"Unknown edit schema reference: {rule['$ref']}")
        for child in rule.get("properties", {}).values():
            check(child)
        for child in rule.get("oneOf", []):
            check(child)
        for field in ("items", "additionalProperties"):
            if isinstance(rule.get(field), dict):
                check(rule[field])

    for spec in schema["$defs"].values():
        check(spec)
    definitions = schema["$defs"]
    limits = {"pages": definitions["DocumentSnapshot"]["properties"]["pages"]["maxItems"],
              "objects": definitions["Page"]["properties"]["annotations"]["maxItems"],
              "pathPoints": definitions["Path"]["properties"]["points"]["maxItems"],
              "pagePoints": schema["x-edit-policy"]["maxPagePoints"],
              "providerDescriptorBytes": schema["x-edit-policy"]["providerDescriptorBytes"],
              "text": definitions["TextBox"]["properties"]["text"]["maxLength"],
              "title": definitions["LibraryItem"]["properties"]["title"]["maxLength"]}
    ts = "// Generated by tools/generate_edit_contracts.py. Do not edit.\n"
    py = "# Generated by tools/generate_edit_contracts.py. Do not edit.\nfrom __future__ import annotations\nfrom typing import Literal, NotRequired, TypedDict\n\n"
    for name, spec in schema["$defs"].items():
        ts += f"export type {name} = {ts_type(spec)};\n"
        if spec.get("type") == "object" and "properties" in spec:
            py += f"class {name}(TypedDict):\n"
            for key, value in spec["properties"].items():
                field = py_type(value)
                if key not in spec["required"]:
                    field = f"NotRequired[{field}]"
                py += f"    {key}: {field}\n"
            py += "\n"
        else:
            py += f"{name} = {py_type(spec)}\n\n"
    ts += "\nexport const EDIT_LIMITS = " + json.dumps(limits, separators=(",", ":")) + " as const;\n"
    ts += "export const CONFLICT_SUFFIX = " + json.dumps(schema["x-edit-policy"]["conflictSuffix"], ensure_ascii=False) + ";\n"
    py += "EDIT_LIMITS = " + repr(limits) + "\nCONFLICT_SUFFIX = " + repr(schema["x-edit-policy"]["conflictSuffix"]) + "\n\n"
    ts += "export const editSchema = " + json.dumps(schema, ensure_ascii=False, separators=(",", ":")) + ";\n"
    # The generated wrappers select the structural validator; no runtime can choose a different schema.
    ts += "import { validateStructure } from './schemaValidator.ts';\n"
    py += "from papeer.core.edit_schema_validator import validate_structure\n\n"
    py += "import json\n_SCHEMA = json.loads(" + repr(json.dumps(schema, ensure_ascii=False, separators=(",", ":"))) + ")\n\n"
    py += "def contract_definitions() -> dict:\n    return json.loads(json.dumps(_SCHEMA['$defs']))\n\n"
    for name in ("Id", "EditBatch", "Snapshot", "Page", "HistoryRecord", "ResourceMetadata", "ContentPublication", "RepositoryCheckpoint", "EditIntentRecord", "EditRecord", "DatasetManifest", "DatasetPublication", "DatasetControlRecord", "CanonicalLibraryProfile", "CanonicalDevicePeer", "CanonicalLocalOwnerGrant", "CanonicalProviderDescriptor", "CanonicalProviderBinding", "CanonicalProviderIntent", "CanonicalInitializeRequest", "CanonicalLibraryInitializationIntent", "LegacyBackupSource", "LegacyBackupEntry", "LegacyBackupManifest", "LegacyBackupPlan", "LegacyMigrationHold", "LegacyMigrationCatalog", "LegacyMigrationInputSet"):
        ts += f"export function validate{name}(value: unknown): asserts value is {name} {{ validateStructure(editSchema, '{name}', value); }}\n"
        py += f"def validate_{name.lower()}(value: object) -> None:\n    validate_structure(_SCHEMA, {name!r}, value)\n\n"
    return {ROOT / "frontend/src/runtime/edits/contracts.ts": ts, ROOT / "papeer/core/edit_contracts.py": py}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated contract differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
